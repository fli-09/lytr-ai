from tests.conftest import chat


def test_same_first_message_in_new_session_hits_cache(client, provider):
    first = chat(client, "s-new-1", "What is the capital of France?").json()
    second = chat(client, "s-new-2", "What is the capital of France?").json()

    assert first["metadata"]["resolution_source"] == "LIVE_INFERENCE"
    assert second["metadata"]["resolution_source"] == "LLM_CACHE"
    assert second["reply"] == first["reply"]
    assert second["metadata"]["key_id"] is None
    assert second["metadata"]["fallback_attempts"] == 0
    # usage stored with the cached response
    assert second["metadata"]["input_tokens"] == first["metadata"]["input_tokens"]
    assert second["metadata"]["output_tokens"] == first["metadata"]["output_tokens"]
    assert second["metadata"]["latency_ms"] < first["metadata"]["latency_ms"]
    assert provider.live_calls_for("What is the capital of France?") >= 1


def test_different_message_never_from_cache(client):
    chat(client, "s-d1", "What is the capital of France?")
    other = chat(client, "s-d2", "What is the capital of Spain?").json()
    assert other["metadata"]["resolution_source"] == "LIVE_INFERENCE"


def test_same_message_different_history_is_not_a_hit(client):
    chat(client, "s-h1", "Hello")
    chat(client, "s-h1", "Tell me more")
    # same new message but different prior context -> different cache key
    chat(client, "s-h2", "Something else")
    r = chat(client, "s-h2", "Tell me more").json()
    assert r["metadata"]["resolution_source"] == "LIVE_INFERENCE"


def test_different_system_prompt_is_not_a_hit(client):
    chat(client, "s-p1", "Hi there")
    r = chat(client, "s-p2", "Hi there", system_prompt="Answer in French.").json()
    assert r["metadata"]["resolution_source"] == "LIVE_INFERENCE"


def test_cache_shared_across_keys(client):
    # Generated by key_2 (key_1 simulated down); then served from cache for a normal request.
    r1 = chat(client, "s-k1", "shared cache across keys", headers={"X-Simulate-Failure": "key_1=429"}).json()
    assert r1["metadata"]["key_id"] == "key_2"
    r2 = chat(client, "s-k2", "shared cache across keys").json()
    assert r2["metadata"]["resolution_source"] == "LLM_CACHE"
    assert r2["reply"] == r1["reply"]


def test_cache_hit_is_persisted_with_cache_metadata(client):
    chat(client, "s-pc1", "persist cache hit")
    chat(client, "s-pc2", "persist cache hit")
    msgs = client.get("/sessions/s-pc2/messages").json()["messages"]
    assert msgs[1]["metadata"]["resolution_source"] == "LLM_CACHE"


def test_tokens_are_per_request_not_running_totals(client):
    a = chat(client, "s-t1", "alpha beta gamma").json()["metadata"]
    b = chat(client, "s-t2", "delta epsilon zeta").json()["metadata"]
    # equal-length first messages in new sessions -> same input tokens
    assert a["input_tokens"] == b["input_tokens"]
    second_turn = chat(client, "s-t1", "eta").json()["metadata"]
    # second turn includes history, but output tokens are only this reply's
    assert second_turn["input_tokens"] > a["input_tokens"]
    assert second_turn["output_tokens"] < second_turn["input_tokens"] + a["output_tokens"]
    assert second_turn["output_tokens"] == len(chat(client, "s-t3", "eta").json()["reply"].split())
