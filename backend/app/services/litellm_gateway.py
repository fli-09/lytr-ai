"""LiteLLM gateway: key pool, ordered failover, built-in cache, failure simulation.

Design (verified against litellm==1.110.3):

* Every (key, model) pair is its own Router model group. Primary-model groups
  are named after the key id (key_1, key_2, ...); backup-model groups are
  key_1@m2, key_2@m2, ... One fallback chain tries every key on the primary
  model first, then every key on each backup model, in order. All failover is
  done by LiteLLM's Router.
* A backup model exists because provider overload ("503 high demand") hits a
  *model*, not a key: when that happens every key on that model fails at once.
* `caching_groups` puts all keys of one model in one cache namespace, so the
  cache key is (model's caching group + full message list + params). The API
  key is not part of LiteLLM's cache key, so a reply generated by key_2 is
  served to a later request that starts at key_1.
* num_retries=0 and disable_cooldowns=True: each key is tried exactly once
  per request, and a failure (real or simulated) never puts a key into a
  global cooldown, so simulation stays request-scoped.
* Simulated failures are injected per deployment through LiteLLM's
  `async_pre_call_deployment_hook`: the selected deployment's call gets a
  `mock_response` exception of the requested status, so the failure travels
  through LiteLLM's normal exception and fallback path.
* Cache hits are detected from `response._hidden_params["cache_hit"]`,
  never from latency.
"""

from __future__ import annotations

import contextvars
import logging
import re
from dataclasses import dataclass, field
from typing import Any

import litellm
from litellm import Router
from litellm.caching.caching import Cache
from litellm.integrations.custom_logger import CustomLogger

logger = logging.getLogger("lyftr.gateway")


_PROVIDER_PREFIX = re.compile(r"^([a-z][a-z0-9_]{1,30}):(.+)$")


def split_key(raw: str) -> tuple[str | None, str]:
    """'groq:gsk_abc' -> ('groq', 'gsk_abc'); a plain key -> (None, key)."""
    match = _PROVIDER_PREFIX.match(raw.strip())
    if match:
        return match.group(1), match.group(2).strip()
    return None, raw.strip()


def provider_of(model: str) -> str:
    return model.split("/", 1)[0] if "/" in model else model


class AllProvidersUnavailable(Exception):
    """Every key in the pool failed for this request."""


@dataclass
class _RequestState:
    simulation: dict[str, int] = field(default_factory=dict)
    attempts: list[str] = field(default_factory=list)


_REQUEST_STATE: contextvars.ContextVar[_RequestState | None] = contextvars.ContextVar(
    "lyftr_request_state", default=None
)


def _simulated_exception(status: int, key_id: str, model: str) -> Exception:
    message = f"simulated HTTP {status} for {key_id} (X-Simulate-Failure)"
    provider = model.split("/", 1)[0] if "/" in model else "unknown"
    if status == 429:
        return litellm.RateLimitError(message=message, llm_provider=provider, model=model)
    if status == 502:
        return litellm.BadGatewayError(message=message, llm_provider=provider, model=model)
    if status == 503:
        return litellm.ServiceUnavailableError(message=message, llm_provider=provider, model=model)
    return litellm.InternalServerError(message=message, llm_provider=provider, model=model)


def _status_of(exc: BaseException) -> int | None:
    status = getattr(exc, "status_code", None)
    return status if isinstance(status, int) else None


class _KeyAttemptHook(CustomLogger):
    """Records each key attempt and injects simulated failures for this request only."""

    def __init__(self, deployment_keys: dict[str, str]) -> None:
        super().__init__()
        self._deployment_keys = deployment_keys  # deployment id -> key id

    async def async_pre_call_deployment_hook(self, kwargs: dict[str, Any], call_type: Any) -> dict[str, Any] | None:
        model_info = kwargs.get("model_info") or {}
        deployment_id = model_info.get("id")
        state = _REQUEST_STATE.get()
        if state is None or deployment_id not in self._deployment_keys:
            return kwargs
        key_id = self._deployment_keys[deployment_id]
        state.attempts.append(deployment_id)
        status = state.simulation.get(key_id)
        if status is not None:
            kwargs["mock_response"] = _simulated_exception(status, key_id, str(kwargs.get("model", "")))
        return kwargs


@dataclass
class GatewayResult:
    reply: str
    resolution_source: str
    model: str
    input_tokens: int
    output_tokens: int
    key_id: str | None
    fallback_attempts: int


class LiteLLMGateway:
    def __init__(
        self,
        api_keys: list[str],
        models: list[str],
        timeout_seconds: float,
        cache_ttl_seconds: int,
    ) -> None:
        if len(api_keys) < 2:
            raise ValueError("at least two API keys are required")
        if not models:
            raise ValueError("at least one model is required")
        self.models = models
        self.key_ids = [f"key_{i}" for i in range(1, len(api_keys) + 1)]
        # A key may be bound to a provider ("groq:gsk_..."); plain keys belong to
        # the primary model's provider. Keys are only paired with their provider's models.
        default_provider = provider_of(models[0])
        key_by_id: dict[str, str] = {}
        provider_by_key: dict[str, str] = {}
        for key_id, raw in zip(self.key_ids, api_keys):
            provider, secret = split_key(raw)
            key_by_id[key_id] = secret
            provider_by_key[key_id] = provider or default_provider
        # deployment id -> (key id, model); primary model first, then backups
        self.deployments: dict[str, tuple[str, str]] = {}
        for m_index, model in enumerate(models):
            matching = [k for k in self.key_ids if provider_by_key[k] == provider_of(model)]
            if not matching:
                raise ValueError(f"no API key configured for model provider '{provider_of(model)}'")
            for key_id in matching:
                dep_id = key_id if m_index == 0 else f"{key_id}@m{m_index + 1}"
                self.deployments[dep_id] = (key_id, model)
        self.deployment_ids = list(self.deployments)

        # LiteLLM built-in cache (in-memory). One process-wide cache.
        litellm.cache = Cache(type="local", ttl=cache_ttl_seconds)
        litellm.suppress_debug_info = True
        litellm.telemetry = False

        self._hook = _KeyAttemptHook({d: k for d, (k, _) in self.deployments.items()})
        litellm.callbacks = [cb for cb in (litellm.callbacks or []) if not isinstance(cb, _KeyAttemptHook)]
        litellm.callbacks.append(self._hook)

        model_list = [
            {
                "model_name": dep_id,
                "litellm_params": {"model": model, "api_key": key_by_id[key_id], "timeout": timeout_seconds},
                "model_info": {"id": dep_id},
            }
            for dep_id, (key_id, model) in self.deployments.items()
        ]
        caching_groups = [
            tuple(d for d, (_, m) in self.deployments.items() if m == model) for model in models
        ]
        self.router = Router(
            model_list=model_list,
            fallbacks=[{self.deployment_ids[0]: self.deployment_ids[1:]}],
            caching_groups=caching_groups,
            num_retries=0,
            disable_cooldowns=True,
            cache_responses=True,
            timeout=timeout_seconds,
        )
        self._warm_cache_imports()

    @staticmethod
    def _warm_cache_imports() -> None:
        # LiteLLM lazily imports a module on the first cache hit; importing it at
        # startup keeps the first cache hit from paying that one-off cost.
        try:
            import litellm.llms.anthropic.messages.native.response_cache  # noqa: F401
        except Exception:  # pragma: no cover - best effort only
            logger.debug("cache warm-up import skipped")

    @property
    def cache_enabled(self) -> bool:
        return litellm.cache is not None

    async def complete(self, messages: list[dict[str, str]], simulation: dict[str, int] | None = None) -> GatewayResult:
        state = _RequestState(simulation=dict(simulation or {}))
        token = _REQUEST_STATE.set(state)
        kwargs: dict[str, Any] = {"caching": True}
        if state.simulation:
            # A failover demo must exercise the key pool, so skip cache *reads*
            # for simulated requests (the fresh result is still written).
            kwargs["cache"] = {"no-cache": True}
        try:
            response = await self.router.acompletion(model=self.deployment_ids[0], messages=messages, **kwargs)
        except Exception as exc:
            logger.warning(
                "all keys failed: attempts=%s final_error=%s status=%s",
                state.attempts, type(exc).__name__, _status_of(exc),
            )
            raise AllProvidersUnavailable() from None
        finally:
            _REQUEST_STATE.reset(token)

        hidden = getattr(response, "_hidden_params", {}) or {}
        cache_hit = hidden.get("cache_hit") is True
        reply = (response.choices[0].message.content or "").strip() if response.choices else ""
        if not reply:
            logger.warning("provider returned an empty reply; attempts=%s", state.attempts)
            raise AllProvidersUnavailable()

        usage = getattr(response, "usage", None)
        input_tokens = int(getattr(usage, "prompt_tokens", 0) or 0)
        output_tokens = int(getattr(usage, "completion_tokens", 0) or 0)

        deployment = hidden.get("model_id")
        if deployment not in self.deployments:
            deployment = state.attempts[-1] if state.attempts else self.deployment_ids[0]
        key_id, model = self.deployments[deployment]

        if cache_hit:
            return GatewayResult(reply, "LLM_CACHE", model, input_tokens, output_tokens, None, 0)

        # every attempt before the successful one failed (each deployment is tried once)
        fallback_attempts = max(len(state.attempts) - 1, 0)
        if fallback_attempts:
            logger.info("answered_by=%s model=%s fallback_attempts=%s", key_id, model, fallback_attempts)
        return GatewayResult(reply, "LIVE_INFERENCE", model, input_tokens, output_tokens, key_id, fallback_attempts)


__all__ = ["AllProvidersUnavailable", "GatewayResult", "LiteLLMGateway"]
